#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub enum PluginWorkflowTaskState {
    Running,
    Dispatching,
    NeedsUserAction,
    Cancelling,
    Cancelled,
    Completed,
    Failed,
    Interrupted,
    CleanupIncomplete,
}

impl PluginWorkflowTaskState {
    #[must_use]
    pub const fn is_terminal(self) -> bool {
        matches!(
            self,
            Self::Cancelled
                | Self::Completed
                | Self::Failed
                | Self::Interrupted
                | Self::CleanupIncomplete
        )
    }
}

