/// UUIDv7 generated by Core for one workflow task. It is a correlation value,
/// not an authorization token.
#[derive(Debug, Clone, PartialEq, Eq, Hash, TS)]
#[ts(type = "string")]
pub struct PluginWorkflowTaskId(String);

impl PluginWorkflowTaskId {
    pub fn parse(value: impl Into<String>) -> Result<Self, &'static str> {
        let value = value.into();
        let parsed =
            Uuid::parse_str(&value).map_err(|_| "plugin_workflow_task_id must be UUIDv7")?;
        if parsed.get_version() != Some(Version::SortRand) {
            return Err("plugin_workflow_task_id must be UUIDv7");
        }
        Ok(Self(parsed.to_string()))
    }

    #[must_use]
    #[cfg(not(target_arch = "wasm32"))]
    pub fn new() -> Self {
        Self(Uuid::now_v7().to_string())
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

#[cfg(not(target_arch = "wasm32"))]
impl Default for PluginWorkflowTaskId {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for PluginWorkflowTaskId {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl FromStr for PluginWorkflowTaskId {
    type Err = &'static str;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        Self::parse(value)
    }
}

impl Serialize for PluginWorkflowTaskId {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        serializer.serialize_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for PluginWorkflowTaskId {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        Self::parse(String::deserialize(deserializer)?).map_err(de::Error::custom)
    }
}

