/// Core sends this bounded event to the same in-process Wasm instance. The
/// event is never read from SQLite and must not be replayed after restart.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum WorkflowEvent {
    Start {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        input_json: Option<String>,
        /// Opaque source-to-task root handle mapping. It exists only for this
        /// in-process start event and is never persisted or replayed.
        #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
        file_scopes: BTreeMap<String, String>,
    },
    StepResult {
        step_id: String,
        reply: PluginApiReply,
    },
    ResourceEvents {
        handle: String,
        events: Vec<PluginApiResourceEvent>,
        backpressured: bool,
    },
}

impl fmt::Debug for WorkflowEvent {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Start {
                input_json,
                file_scopes,
            } => formatter
                .debug_struct("WorkflowEvent::Start")
                .field(
                    "input_json",
                    &input_json
                        .as_ref()
                        .map(|value| format!("[REDACTED; {} bytes]", value.len())),
                )
                .field(
                    "file_scopes",
                    &format_args!("[OPAQUE; {} handles]", file_scopes.len()),
                )
                .finish(),
            Self::StepResult { step_id, .. } => formatter
                .debug_struct("WorkflowEvent::StepResult")
                .field("step_id", step_id)
                .field("reply", &"[REDACTED]")
                .finish(),
            Self::ResourceEvents {
                handle,
                events,
                backpressured,
            } => formatter
                .debug_struct("WorkflowEvent::ResourceEvents")
                .field("handle", handle)
                .field("event_count", &events.len())
                .field("backpressured", backpressured)
                .finish(),
        }
    }
}

/// A Wasm workflow transition. Core accepts at most one typed API call for
/// the requested fixed step, then gives its reply back as a later event.
/// With neither a call nor completion, Core waits for an already-owned resource event.
/// Waiting without any task resource is rejected instead of leaving an inert task running.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct WorkflowResponse {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub step_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub call: Option<PluginApiCall>,
    pub complete: bool,
}

/// One Core-correlated request to the resident Wasm workflow handler.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PluginWorkflowEvent {
    pub task_id: PluginWorkflowTaskId,
    pub workflow_id: String,
    pub event: WorkflowEvent,
}

impl fmt::Debug for WorkflowResponse {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("WorkflowResponse")
            .field("step_id", &self.step_id)
            .field("call", &self.call.as_ref().map(|_| "[REDACTED]"))
            .field("complete", &self.complete)
            .finish()
    }
}

#[must_use]
pub fn valid_plugin_workflow_id(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= MAX_PLUGIN_WORKFLOW_ID_BYTES
        && value.is_ascii()
        && value
            .bytes()
            .next()
            .is_some_and(|byte| byte.is_ascii_alphanumeric())
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn workflow_ids_are_bounded_ascii_identifiers() {
        assert!(valid_plugin_workflow_id("backup.daily"));
        assert!(valid_plugin_workflow_id("A_1-step"));
        assert!(!valid_plugin_workflow_id(""));
        assert!(!valid_plugin_workflow_id(".leading"));
        assert!(!valid_plugin_workflow_id("contains space"));
        assert!(!valid_plugin_workflow_id(&"a".repeat(65)));
    }
}
