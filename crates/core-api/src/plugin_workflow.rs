/// This request may carry package-defined JSON input only in process memory.
/// It must never be logged, persisted, fingerprinted, or replayed after a
/// restart.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PluginWorkflowTaskStartRequest {
    pub meta: RequestMeta,
    pub plugin_id: PluginId,
    #[serde(rename = "artifactFingerprintSha256")]
    pub signer_fingerprint_sha256: String,
    pub expected_package_sha256: String,
    pub expected_state_version: WireSequence,
    pub instance_generation: WireSequence,
    pub workflow_id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub input_json: Option<String>,
    /// Opaque, Core-issued file root handles selected before an explicit task
    /// start. Core adopts them into the task consumer and gives the Wasm
    /// instance only the old-to-new handle map in its in-memory start event.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub file_scope_handles: Vec<String>,
}

impl fmt::Debug for PluginWorkflowTaskStartRequest {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("PluginWorkflowTaskStartRequest")
            .field("request_id", &self.meta.request_id)
            .field("plugin_id", &self.plugin_id)
            .field("workflow_id", &self.workflow_id)
            .field(
                "input_json",
                &self
                    .input_json
                    .as_ref()
                    .map(|value| format!("[REDACTED; {} bytes]", value.len())),
            )
            .field(
                "file_scope_handles",
                &format_args!("[OPAQUE; {} handles]", self.file_scope_handles.len()),
            )
            .finish_non_exhaustive()
    }
}

