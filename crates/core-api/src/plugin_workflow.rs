//! Bounded, Core-owned plugin workflow wire types.
//!
//! A workflow catalog is immutable package metadata. It names the only step
//! identifiers a running Wasm instance may use, but it is deliberately not an
//! executable plan and grants no capability. The actual next API call is
//! produced one event at a time by the running plugin instance and brokered by
//! Core.

